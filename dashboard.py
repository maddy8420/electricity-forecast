with tab5:
    st.subheader("Energy Mix Builder")

    if source_hist is None:
        st.info(
            "Per-source forecasts not found. Run `python source_forecast.py` "
            "to create source_forecasts_2040.xlsx, then reload this page."
        )
    else:
        st.warning(
            "Each source is forecast separately from only ~50 months of reliable "
            "history (Dec 2018 to Mar 2023) with an untuned seasonal model. Treat "
            "these as trend scenarios, not predictions. The combined total only "
            "counts the sources you select, so it answers 'what if the mix were "
            "only these sources', not 'what will total supply be'."
        )

        all_sources = sorted(source_hist["source"].unique())

        left, right = st.columns([2, 1])
        picked = left.multiselect("Sources to include", all_sources, default=all_sources)
        view = right.radio(
            "Show", ["History + forecast", "History only", "Forecast only"],
            horizontal=True,
        )
        year_from, year_to = st.slider("Year range", 2018, 2040, (2018, 2040))

        opt1, opt2, opt3 = st.columns(3)
        show_band = opt1.checkbox("95% confidence bands", value=False)
        show_demand = opt2.checkbox("Demand (trend model)", value=True)
        show_cea = opt3.checkbox("CEA official demand points", value=True)

        if not picked:
            st.info("Pick at least one source to see the charts.")
        else:
            x_range = [pd.Timestamp(f"{year_from}-01-01"), pd.Timestamp(f"{year_to}-12-31")]
            show_hist = view != "Forecast only"
            show_fc = view != "History only"

            # --- Chart 1: each selected source on its own line ---
            fig = go.Figure()
            for i, name in enumerate(picked):
                color = qualitative.Plotly[i % len(qualitative.Plotly)]
                h = source_hist[source_hist["source"] == name]
                f = source_fc[source_fc["source"] == name]
                if show_hist:
                    fig.add_trace(go.Scatter(
                        x=h["date"], y=h["value"], mode="lines",
                        name=f"{name} (history)", line=dict(color=color)))
                if show_fc:
                    fig.add_trace(go.Scatter(
                        x=f["date"], y=f["forecast"], mode="lines",
                        name=f"{name} (forecast)", line=dict(color=color, dash="dash")))
                    if show_band:
                        fig.add_trace(go.Scatter(
                            x=list(f["date"]) + list(f["date"][::-1]),
                            y=list(f["ci_upper_95"]) + list(f["ci_lower_95"][::-1]),
                            fill="toself", fillcolor=hex_to_rgba(color, 0.15),
                            line=dict(width=0), showlegend=False, hoverinfo="skip"))
            fig.update_layout(height=500, xaxis_title="Date",
                              yaxis_title="Avg daily generation (MU)")
            fig.update_xaxes(range=x_range)
            st.plotly_chart(fig, use_container_width=True)

            # --- Chart 2: combined selected mix vs demand ---
            hist_total = (source_hist[source_hist["source"].isin(picked)]
                          .groupby("date")["value"].sum())
            fc_total = (source_fc[source_fc["source"].isin(picked)]
                        .groupby("date")["forecast"].sum())

            fig2 = go.Figure()
            if show_hist:
                fig2.add_trace(go.Scatter(
                    x=hist_total.index, y=hist_total.values, mode="lines",
                    name="Selected mix (history)", line=dict(color="black")))
            if show_fc:
                fig2.add_trace(go.Scatter(
                    x=fc_total.index, y=fc_total.values, mode="lines",
                    name="Selected mix (forecast)", line=dict(color="black", dash="dash")))
            if show_demand:
                if show_hist:
                    demand_hist = master.set_index("date")["avg_daily_demand"].dropna()
                    fig2.add_trace(go.Scatter(
                        x=demand_hist.index, y=demand_hist.values, mode="lines",
                        name="Demand (history)", line=dict(color="red", width=1)))
                if show_fc:
                    fig2.add_trace(go.Scatter(
                        x=demand_fc.index, y=demand_fc["forecast"], mode="lines",
                        name="Demand (trend forecast)", line=dict(color="red", dash="dash")))
            if show_cea and show_fc:
                fig2.add_trace(go.Scatter(
                    x=list(CEA_DEMAND_BU.keys()),
                    y=[bu_to_avg_daily_mu(v) for v in CEA_DEMAND_BU.values()],
                    mode="markers", name="CEA official demand",
                    marker=dict(color="darkred", size=11, symbol="diamond")))
            fig2.update_layout(height=450, xaxis_title="Date",
                               yaxis_title="Avg daily (MU)",
                               title="Selected mix vs demand")
            fig2.update_xaxes(range=x_range)
            st.plotly_chart(fig2, use_container_width=True)

            # --- Checkpoint table ---
            rows = []
            for year in CHECKPOINT_YEARS:
                d = pd.Timestamp(f"{year}-12-01")
                if d not in fc_total.index or d not in demand_fc.index:
                    continue
                mix_val = fc_total.loc[d]
                trend_val = demand_fc.loc[d, "forecast"]
                cea_bu = CEA_DEMAND_BU.get(d)
                rows.append({
                    "Year": year,
                    "Selected mix (MU/day)": f"{mix_val:,.0f}",
                    "Trend demand (MU/day)": f"{trend_val:,.0f}",
                    "Mix minus trend demand": f"{mix_val - trend_val:+,.0f}",
                    "CEA demand (MU/day)": (f"{bu_to_avg_daily_mu(cea_bu):,.0f}"
                                            if cea_bu else "n/a"),
                })
            if rows:
                st.table(pd.DataFrame(rows).set_index("Year"))
            st.caption(
                "CEA figures are energy requirement from its Electric Power Survey "
                "projections and are only published for 2026-27, 2031-32 and 2035-36 "
                "(plotted at the matching December). The trend demand series is "
                "'energy met', so the two are close but not identical measures."
            )



# ----------------------------------------------------------------------
# TAB 6 — Date Predictor
# ----------------------------------------------------------------------

with tab6:
    st.subheader("Date Predictor — Expected National Electricity Demand")
    st.caption(
        "Pick any date between April 2013 and December 2040. "
        "The app applies a day-of-week seasonal profile on top of the monthly "
        "baseline (historical data, reported consumption, or SARIMA forecast) "
        "to estimate that day's demand."
    )

    # Load the daily data and build the profile (cached)
    _daily_df = load_daily_demand()

    # master_monthly for predict_day needs year_month as plain string "YYYY-MM"
    _master_for_pred = master.copy()
    _master_for_pred["year_month"] = _master_for_pred["year_month"].astype(str).str[:7]
    if "low_coverage_flag" not in _master_for_pred.columns:
        _master_for_pred["low_coverage_flag"] = False

    _profile = load_day_profile(_daily_df)

    # Date picker
    picked_date = st.date_input(
        "Date",
        value=date(2027, 4, 15),
        min_value=date(2013, 4, 1),
        max_value=date(2040, 12, 31),
    )

    # Run prediction
    _demand_fc, _gen_fc = load_forecasts()
    _result = predict_day(
        picked_date,
        demand_fc=_demand_fc,
        gen_fc=_gen_fc,
        daily=_daily_df,
        master_monthly=_master_for_pred,
        profile=_profile,
    )

    # ---- Handle out-of-range / insufficient data ----
    if _result.get("mode") in ("out_of_range",) or _result.get("baseline_mu") is None:
        st.warning(
            "\n".join(_result.get("notes", ["No data available for this date."]))
        )
    else:
        _mode      = _result["mode"]
        _est       = _result["estimate_mu"]
        _low       = _result["low_mu"]
        _high      = _result["high_mu"]
        _baseline  = _result["baseline_mu"]
        _wf        = _result["weekday_factor"]
        _hname     = _result["holiday_name"]
        _hmult     = _result["holiday_mult"]
        _peak_mw   = _result["peak_mw_estimate"]
        _actual    = _result.get("actual_mu")
        _validated = _result["validated"]

        # Delta vs flat month average
        _delta_pct = (_wf - 1.0) * 100.0
        _delta_str = f"{_delta_pct:+.1f}% vs month average"

        # ---- Metrics row ----
        _mc1, _mc2 = st.columns(2)
        if _mode == "historical":
            _baseline_label = "Monthly baseline (avg energy met, cleaned)"
        elif _mode == "actual_monthly":
            _baseline_label = "Monthly baseline (reported consumption)"
        else:
            _baseline_label = "Monthly baseline (SARIMA demand forecast)"

        _mc1.metric(
            "Expected demand (MU/day)",
            f"{_est:,.1f}",
            delta=_delta_str,
        )
        if _peak_mw is not None:
            _mc2.metric("Approx. peak (MW)", f"{_peak_mw:,.0f}")
            _mc2.caption(
                "Sum of state-level daily maxima (non-coincident). "
                "True simultaneous national peak is lower (~230\u2013250 GW at current levels)."
            )

        st.caption(
            f"Plausible range: **{_low:,.1f}** to **{_high:,.1f}** MU/day  "
            f"(approximate 90% intra-month band \u00d7 95% monthly CI)"
        )

        # ---- Confidence message ----
        if _mode == "historical":
            _msg = (
                f"This date is in the **historical record** (data up to Mar 2023). "
                f"Month average (cleaned): **{_baseline:,.1f} MU/day**."
            )
            if _actual is not None:
                _err = abs(_actual - _est)
                _msg += (
                    f" Reported actual for this day: **{_actual:,.1f} MU/day** "
                    f"(estimate error: {_err:,.1f} MU)."
                )
            st.info(_msg)

        elif _mode == "actual_monthly":
            _msg = (
                f"Baseline from **reported monthly consumption** "
                f"(Apr 2023 \u2013 last available month). "
                f"Monthly baseline: **{_baseline:,.1f} MU/day**."
            )
            _notes_text = " ".join(_result.get("notes", []))
            if "calibration" in _notes_text.lower():
                _msg += " Consumption adjusted by historical calibration ratio."
            st.info(_msg)

        elif _mode == "forecast" and _validated:
            st.success(
                f"Month is within the **empirically validated 24-month forecast horizon** "
                f"(SARIMA walk-forward tested). Month baseline: **{_baseline:,.1f} MU/day**."
            )
        elif _mode == "forecast" and not _validated:
            st.warning(
                "\u26a0 Scenario extrapolation beyond the validated 24-month horizon \u2014 "
                "treat as indicative trend, not a precise prediction. "
                f"Month baseline: **{_baseline:,.1f} MU/day**."
            )

        if _result["notes"]:
            for _n in _result["notes"]:
                st.caption(f"\u2139 {_n}")

        # ---- Context panel ----
        with st.expander("Context & components", expanded=True):
            _ctx1, _ctx2 = st.columns(2)
            with _ctx1:
                st.write(f"**{_baseline_label}:** {_baseline:,.1f} MU/day")
                st.write(f"**Weekday factor:** {_wf:.4f} ({pd.Timestamp(picked_date).day_name()})")
                if _hname:
                    st.write(f"**Holiday:** {_hname} (multiplier: {_hmult:.4f})")
                else:
                    st.write("**Holiday:** None")
                _n_flagged = sum(_profile.get("flagged_per_year", {}).values())
                if _n_flagged > 0:
                    st.caption(
                        f"\u2139 {_n_flagged} days with implausible spikes in the source data "
                        f"are excluded from the profile and baseline computation."
                    )
            with _ctx2:
                _ms = pd.Timestamp(picked_date).to_period("M").to_timestamp()
                _gap_df = load_gap()
                if _ms in _gen_fc.index:
                    st.write(f"**Generation forecast (month):** {_gen_fc.loc[_ms, 'forecast']:,.1f} MU/day")
