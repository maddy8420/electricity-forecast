"""
India Electricity Forecasting — Interactive Dashboard
--------------------------------------------------------
Combines every output from the pipeline into one browsable app.

Run with:
    streamlit run dashboard.py

Expects these files in the same folder (all generated by earlier scripts):
    india_electricity_master.xlsx
    avg_daily_demand_forecast_2040.xlsx
    avg_daily_generation_forecast_2040.xlsx
    demand_supply_gap.xlsx
    source_forecasts_2040.xlsx        (from source_forecast.py; Mix Builder tab)
"""

from pathlib import Path
from datetime import date

import streamlit as st
import pandas as pd
import plotly.graph_objects as go
from plotly.colors import qualitative
from plotly.subplots import make_subplots
from daily_predictor import build_profile, predict_day, backtest

st.set_page_config(page_title="India Electricity Forecast", layout="wide")

BASE_DIR = Path(__file__).resolve().parent
MASTER_FILE = BASE_DIR / "india_electricity_master.xlsx"
DEMAND_FORECAST_FILE = BASE_DIR / "avg_daily_demand_forecast_2040.xlsx"
GENERATION_FORECAST_FILE = BASE_DIR / "avg_daily_generation_forecast_2040.xlsx"
GAP_FILE = BASE_DIR / "demand_supply_gap.xlsx"
SOURCE_FORECAST_FILE = BASE_DIR / "source_forecasts_2040.xlsx"

ERA_CUTOFF = pd.Timestamp("2017-05-26")
CHECKPOINT_YEARS = [2026, 2030, 2035, 2040]

# CEA official energy requirement (Billion Units), see cea_benchmark.py for sources.
# Converted to avg daily MU so it can sit on the same axis as the forecasts.
CEA_DEMAND_BU = {
    pd.Timestamp("2026-12-01"): 1907.8,
    pd.Timestamp("2032-12-01"): 2473.8,
    pd.Timestamp("2035-12-01"): 3365.0,
}


def bu_to_avg_daily_mu(bu):
    """Annual Billion Units -> average daily Million Units."""
    return bu * 1000 / 365


def hex_to_rgba(hex_color, alpha):
    """'#636EFA' -> 'rgba(99,110,250,alpha)' for translucent confidence bands."""
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return f"rgba({r},{g},{b},{alpha})"


# ----------------------------------------------------------------------
# DATA LOADING (cached so the app doesn't re-read files on every click)
# ----------------------------------------------------------------------

@st.cache_data
def load_master():
    master = pd.read_excel(MASTER_FILE, sheet_name="MASTER_monthly")
    master["year_month"] = pd.PeriodIndex(master["year_month"], freq="M")
    master["date"] = master["year_month"].dt.to_timestamp()
    master = master.sort_values("date").reset_index(drop=True)
    harmonized = pd.read_excel(MASTER_FILE, sheet_name="gen_by_source_harmonized")
    harmonized["date"] = pd.to_datetime(harmonized["date"])
    return master, harmonized


@st.cache_data
def load_forecasts():
    demand = pd.read_excel(DEMAND_FORECAST_FILE, index_col=0)
    demand.index = pd.to_datetime(demand.index)
    generation = pd.read_excel(GENERATION_FORECAST_FILE, index_col=0)
    generation.index = pd.to_datetime(generation.index)
    return demand, generation


@st.cache_data
def load_gap():
    gap = pd.read_excel(GAP_FILE, index_col=0)
    gap.index = pd.to_datetime(gap.index)
    return gap


@st.cache_data
def load_source_forecasts():
    """Per-source history and forecast (long format: one row per source per month)."""
    history = pd.read_excel(SOURCE_FORECAST_FILE, sheet_name="history")
    forecast = pd.read_excel(SOURCE_FORECAST_FILE, sheet_name="forecast")
    history["date"] = pd.to_datetime(history["date"])
    forecast["date"] = pd.to_datetime(forecast["date"])
    return history, forecast


@st.cache_data
def load_daily_demand():
    """Daily national demand sheet from the master workbook."""
    df = pd.read_excel(MASTER_FILE, sheet_name="national_demand_daily")
    df["date"] = pd.to_datetime(df["date"])
    return df


@st.cache_data
def load_day_profile(_daily_df):
    """Build the intra-month weekday profile from the daily demand data."""
    return build_profile(_daily_df)


@st.cache_data
def load_backtest(_daily_df):
    """Run the 12-month holdout backtest on the weekday profile."""
    return backtest(_daily_df, holdout_months=12)


data_loaded = False
missing_file = ""

try:
    master, harmonized = load_master()
    demand_fc, generation_fc = load_forecasts()
    gap_df = load_gap()
    data_loaded = True
except Exception as e:
    data_loaded = False
    missing_file = str(e)

# The Mix Builder tab is optional: the other tabs still work without it.
try:
    source_hist, source_fc = load_source_forecasts()
except Exception:
    source_hist, source_fc = None, None

st.title("India Electricity Demand, Generation & Energy Mix Forecast")

if not data_loaded:
    st.error(
        "Could not load the required dashboard data.\n\n"
        f"Detail: {missing_file}\n\n"
        "Make sure the pipeline output files exist in the same folder as this "
        "dashboard script and that you have run the full pipeline before opening "
        "the dashboard."
    )
    st.stop()


